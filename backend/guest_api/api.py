@guest_session_router.get("/session/{qr_token}", response=TableSessionOut)
def resolve_guest_session(request, qr_token: UUID):
    """Resolve a table QR token into the active guest session identity."""
    table = get_object_or_404(Table, qr_token=qr_token)
    session = (
        TableSession.objects
        .filter(table=table, status=TableSession.Status.ACTIVE)
        .order_by("-started_at")
        .first()
    )
    if session is None:
        session = TableSession.objects.create(table=table)

    return TableSessionOut(
        session_token=str(session.session_token),
        table_id=table.id,
        table_number=str(table.number),
        table_label=f"Table {table.number}",
        status=session.status,
        started_at=session.started_at,
        ended_at=session.ended_at,
    )


