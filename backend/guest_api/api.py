@guest_session_router.get("/menu/items/{item_id}", response=MenuItemDetailOut)
def get_guest_item(request, item_id: int, source: str = ""):
    """Return one available dine-in product with its ingredients.

    `source` ("menu_item" or "product") disambiguates item_id, since
    MenuItem and Product have independent auto-increment ids that can
    collide. Without it, this falls back to the old best-effort order
    (MenuItem first, then Product) for backward compatibility with
    older cart entries saved before "source" existed.
    """
    def _from_menu_item(item):
        ingredients = []
        for index, ingredient in enumerate(item.ingredients or [], start=1):
            if isinstance(ingredient, dict):
                ingredients.append({
                    "id": ingredient.get("id", index),
                    "name": ingredient.get("name", ""),
                    "allergen": ingredient.get("allergen", False),
                })
            else:
                ingredients.append({"id": index, "name": str(ingredient), "allergen": False})
        return MenuItemDetailOut(
            id=item.id,
            name=item.name,
            price=item.price,
            image_url=item.photo.url if item.photo else None,
            category_id=item.category_id,
            description=item.description,
            ingredients=ingredients,
        )

    def _from_product(prod):
        desc_ings = [s.strip() for s in (prod.description or "").split(",") if s.strip()][:8]
        ingredients = [{"id": i + 1, "name": name, "allergen": False} for i, name in enumerate(desc_ings)]
        return MenuItemDetailOut(
            id=prod.id,
            name=prod.name,
            price=prod.price,
            image_url=prod.image_url or None,
            category_id=getattr(prod, 'category_id', None),
            description=prod.description or "",
            ingredients=ingredients,
        )

    if source == "product":
        prod = Product.objects.filter(id=item_id, is_available=True).first()
        if prod is None:
            raise HttpError(404, "Not Found: No Product matches the given query.")
        return _from_product(prod)

    if source == "menu_item":
        item = MenuItem.objects.filter(id=item_id, is_available_now=True).first()
        if item is None:
            raise HttpError(404, "Not Found: No MenuItem matches the given query.")
        return _from_menu_item(item)

    # No source given — legacy best-effort fallback for old cart entries.
    item = MenuItem.objects.filter(id=item_id, is_available_now=True).first()
    if item is not None:
        return _from_menu_item(item)
    prod = Product.objects.filter(id=item_id, is_available=True).first()
    if prod is None:
        raise HttpError(404, "Not Found: No MenuItem matches the given query.")
    return _from_product(prod)


@guest_session_router.get("/cart", response=list[GuestCartItemOut])
def get_guest_cart(request):
    """Return the current guest cart stored in the Django session."""
    return request.session.get(_guest_cart_key(request), [])


def _guest_cart_key(request) -> str:
    token = request.headers.get("X-Table-Session")
    if not token:
        raise HttpError(401, "A table session is required")
    if not TableSession.objects.filter(
        session_token=token, status=TableSession.Status.ACTIVE
    ).exists():
        raise HttpError(401, "The table session is invalid or expired")
    return f"guest_cart:{token}"


@guest_session_router.post("/cart/items", response=GuestCartItemOut)
def add_guest_cart_item(request, data: GuestCartItemIn):
    key = _guest_cart_key(request)
    cart = request.session.get(key, [])

    # item_id alone is ambiguous: MenuItem and Product have independent
    # auto-increment ids that can collide (e.g. MenuItem id=1 and Product
    # id=1 are unrelated rows). If the client tells us the source, trust
    # it. Otherwise fall back to the old best-effort guess for legacy
    # callers that don't send it yet.
    item = None
    product_fallback = None
    source = data.source

    if source == "product":
        product_fallback = Product.objects.filter(id=data.item_id, is_available=True).first()
        if product_fallback is None:
            raise HttpError(404, "Item not found")
    elif source == "menu_item":
        item = MenuItem.objects.filter(id=data.item_id, is_available_now=True).first()
        if item is None:
            raise HttpError(404, "Item not found")
    else:
        try:
            item = MenuItem.objects.get(id=data.item_id, is_available_now=True)
            source = "menu_item"
        except MenuItem.DoesNotExist:
            product_fallback = Product.objects.filter(id=data.item_id, is_available=True).first()
            if product_fallback is None:
                raise HttpError(404, "Item not found")
            source = "product"

    resolved_id = item.id if item is not None else product_fallback.id
    image_url = (item.photo.url if item and item.photo else "") if item is not None else (product_fallback.image_url or "")

    existing = next(
        (entry for entry in cart
         if entry["item_id"] == resolved_id
         and entry.get("source") == source
         and entry["excluded_ingredients"] == data.excluded_ingredients),
        None,
    )

    if existing:
        existing["quantity"] += 1
        result = existing
    else:
        name = item.name if item is not None else product_fallback.name
        result = {
            "cart_item_id": f"{source}:{resolved_id}:{len(cart)}",
            "item_id": resolved_id,
            "source": source,
            "name": name,
            "photo_url": image_url,
            "quantity": 1,
            "excluded_ingredients": data.excluded_ingredients,
        }
        cart.append(result)

    request.session[key] = cart
    request.session.modified = True
    return result


def _get_or_create_menu_item_for_product(product: Product) -> MenuItem:
    """Legacy Product objects have no dine-in MenuItem counterpart, but
    RestaurantOrderItem requires one (menu_item is a required FK). Mirror
    the Product into a MenuItem on first use, then reuse it afterward —
    matched by name to avoid creating duplicates on every order."""
    legacy_category, _ = MenuCategory.objects.get_or_create(
        slug="legacy-catalog",
        defaults={"name": "Catalog items", "display_order": 999},
    )
    menu_item, _ = MenuItem.objects.get_or_create(
        category=legacy_category,
        name=product.name,
        defaults={
            "description": product.description or "",
            "ingredients": [],
            "price": product.active_price,
            "is_available_now": True,
        },
    )
    return menu_item


@guest_session_router.post("/orders", response=GuestOrderOut)
def submit_guest_order(request):
    """Move the draft cart into a real RestaurantOrder (DB), retaining
    exclusions, so staff (table_detail / /api/staff/orders/pending) sees it."""
    token = request.headers.get("X-Table-Session")
    key = _guest_cart_key(request)
    cart = request.session.get(key, [])
    if not cart:
        raise HttpError(400, "Cart is empty")

    session = get_object_or_404(
        TableSession, session_token=token, status=TableSession.Status.ACTIVE
    )

    order = RestaurantOrder.objects.create(session=session)

    order_items = []
    for line in cart:
        menu_item = None
        source = line.get("source")

        if source == "product":
            product = Product.objects.filter(id=line["item_id"]).first()
            if product is not None:
                menu_item = _get_or_create_menu_item_for_product(product)
        elif source == "menu_item":
            menu_item = MenuItem.objects.filter(id=line["item_id"]).first()
        else:
            # Legacy cart lines saved before "source" existed.
            menu_item = MenuItem.objects.filter(id=line["item_id"]).first()
            if menu_item is None:
                product = Product.objects.filter(id=line["item_id"]).first()
                if product is not None:
                    menu_item = _get_or_create_menu_item_for_product(product)

        if menu_item is None:
            continue

        order_items.append(RestaurantOrderItem(
            order=order,
            menu_item=menu_item,
            quantity=line.get("quantity", 1),
            excluded_ingredients=line.get("excluded_ingredients", []),
        ))

    if not order_items:
        order.delete()
        raise HttpError(400, "Cart contains no orderable dine-in items")

    RestaurantOrderItem.objects.bulk_create(order_items)

    request.session[key] = []
    request.session.modified = True

    waiter = session.table.assigned_waiter
    if waiter is not None:
        notify_waiter(waiter.id, "order.submitted", {
            "order_id": order.id,
            "table_number": session.table.number,
        })

    return {
        "id": order.id,
        "status": order.status,
        "placed_at": order.submitted_at.isoformat(),
        "items": cart,
    }


@guest_session_router.get("/orders", response=list[GuestOrderOut])
def list_guest_orders(request):
    token = request.headers.get("X-Table-Session")
    _guest_cart_key(request)
    orders = (
        RestaurantOrder.objects
        .filter(session__session_token=token)
        .prefetch_related("items__menu_item")
        .order_by("submitted_at")
    )
    return [
        {
            "id": o.id,
            "status": o.status,
            "placed_at": o.submitted_at.isoformat(),
            "items": [
                {
                    "cart_item_id": f"{it.menu_item_id}:{it.id}",
                    "item_id": it.menu_item_id,
                    "name": it.menu_item.name,
                    "quantity": it.quantity,
                    "excluded_ingredients": it.excluded_ingredients,
                }
                for it in o.items.all()
            ],
        }
        for o in orders
    ]


@guest_session_router.get("/bill", response=GuestBillOut)
def get_guest_bill(request):
    token = request.headers.get("X-Table-Session")
    _guest_cart_key(request)
    orders = (
        RestaurantOrder.objects
        .filter(session__session_token=token)
        .prefetch_related("items__menu_item")
        .order_by("submitted_at")
    )
    total = Decimal("0")
    bill_orders = []
    for order in orders:
        bill_items = []
        for it in order.items.all():
            price_val = it.menu_item.price
            photo_url = it.menu_item.photo.url if it.menu_item.photo else ""
            subtotal = price_val * it.quantity
            total += subtotal
            bill_items.append(GuestBillItemOut(
                cart_item_id=f"{it.menu_item_id}:{it.id}",
                item_id=it.menu_item_id,
                name=it.menu_item.name,
                quantity=it.quantity,
                excluded_ingredients=it.excluded_ingredients,
                price=price_val,
                subtotal=subtotal,
                photo_url=photo_url,
            ))
        bill_orders.append(GuestBillOrderOut(
            id=order.id,
            status=order.status,
            placed_at=order.submitted_at.isoformat(),
            items=bill_items,
        ))
    return {"total": total, "currency": "UZS", "orders": bill_orders}

@guest_session_router.post("/payment")
def request_guest_payment(request, data: GuestPaymentIn):
    """Record the guest's Card/Cash request for the active table session."""
    if data.method not in {"card", "cash"}:
        raise HttpError(400, "Payment method must be 'card' or 'cash'")
    token = request.headers.get("X-Table-Session")
    _guest_cart_key(request)
    payment_key = f"guest_payment:{token}"
    if request.session.get(payment_key, {}).get("status") == "requested":
        raise HttpError(409, "Payment has already been requested for this session")

    session = get_object_or_404(
        TableSession,
        session_token=token,
        status=TableSession.Status.ACTIVE,
    )
    request.session[payment_key] = {
        "method": data.method,
        "status": "requested",
    }
    request.session.modified = True

    waiter = session.table.assigned_waiter
    if waiter is not None:
        notify_waiter(waiter.id, "payment.requested", {
            "session_token": str(session.session_token),
            "table_number": session.table.number,
            "method": data.method,
        })

    return {"status": "requested"}

